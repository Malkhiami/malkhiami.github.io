"""Generate assets/docs/Al-Khiami-publications.bib from data/publications.json.

Run after editing publications:  python scripts/generate_bibtex.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PUBS = json.loads((ROOT / "data" / "publications.json").read_text(encoding="utf-8"))["publications"]
OUT = ROOT / "assets" / "docs" / "Al-Khiami-publications.bib"

ENTRY_TYPE = {"journal": "article", "conference": "inproceedings", "chapter": "incollection"}


def main() -> None:
    entries, used_keys = [], set()
    for pub in sorted(PUBS, key=lambda p: (-p["year"], p["title"])):
        first = re.sub(r"[^A-Za-z]", "", pub["authors"].split(",")[0])
        key = base = f"{first}{pub['year']}"
        suffix = ord("a")
        while key in used_keys:
            key = base + chr(suffix)
            suffix += 1
        used_keys.add(key)

        etype = ENTRY_TYPE.get(pub["type"], "misc")
        venue_field = "journal" if pub["type"] == "journal" else "booktitle"
        lines = [
            f"@{etype}{{{key},",
            f"  author = {{{pub['authors'].replace('&', 'and')}}},",
            f"  title  = {{{pub['title']}}},",
            f"  {venue_field} = {{{pub['venue']}}},",
            f"  year   = {{{pub['year']}}},",
        ]
        if pub.get("doi"):
            lines.append(f"  doi    = {{{pub['doi']}}},")
        if pub.get("url"):
            lines.append(f"  url    = {{{pub['url']}}},")
        lines[-1] = lines[-1].rstrip(",")
        lines.append("}")
        entries.append("\n".join(lines))

    OUT.write_text(
        "% Publications of Mohamad Iyad Al-Khiami\n"
        "% Generated by scripts/generate_bibtex.py\n\n" + "\n\n".join(entries) + "\n",
        encoding="utf-8",
    )
    print(f"{len(entries)} entries -> {OUT.name}")


if __name__ == "__main__":
    main()
