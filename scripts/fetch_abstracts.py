"""Fetch publication abstracts from Crossref by DOI and generate data/publications.js.

Usage:  python scripts/fetch_abstracts.py
Only fills abstracts that are currently empty, so manual edits in
publications.json are preserved.
"""
import json
import re
import sys
import time
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
JSON_PATH = ROOT / "data" / "publications.json"
JS_PATH = ROOT / "data" / "publications.js"

HEADERS = {"User-Agent": "AlKhiami-academic-site/1.0 (mailto:m.iyadalkh@gmail.com)"}


def strip_jats(text: str) -> str:
    text = re.sub(r"<jats:title[^>]*>.*?</jats:title>", " ", text, flags=re.S)
    text = re.sub(r"<[^>]+>", " ", text)
    text = re.sub(r"\s+", " ", text)
    return text.strip()


def fetch_abstract(doi: str) -> str:
    url = f"https://api.crossref.org/works/{urllib.parse.quote(doi)}"
    req = urllib.request.Request(url, headers=HEADERS)
    with urllib.request.urlopen(req, timeout=30) as resp:
        data = json.loads(resp.read().decode("utf-8"))
    return strip_jats(data.get("message", {}).get("abstract", "") or "")


def main() -> None:
    payload = json.loads(JSON_PATH.read_text(encoding="utf-8"))
    pubs = payload["publications"]
    found, missing = 0, []

    for pub in pubs:
        if pub.get("abstract") or not pub.get("doi"):
            continue
        try:
            abstract = fetch_abstract(pub["doi"])
        except Exception as exc:  # noqa: BLE001 - report and continue
            print(f"  ! {pub['id']}: {exc}")
            missing.append(pub["id"])
            continue
        if abstract:
            pub["abstract"] = abstract
            found += 1
            print(f"  + {pub['id']}: {len(abstract)} chars")
        else:
            missing.append(pub["id"])
            print(f"  - {pub['id']}: no abstract deposited")
        time.sleep(0.5)

    JSON_PATH.write_text(json.dumps(payload, indent=2, ensure_ascii=False), encoding="utf-8")
    JS_PATH.write_text(
        "// Generated by scripts/fetch_abstracts.py — edit data/publications.json instead.\n"
        "const PUBLICATIONS = " + json.dumps(pubs, indent=2, ensure_ascii=False) + ";\n",
        encoding="utf-8",
    )
    print(f"\nDone. {found} abstracts added, {len(missing)} without: {', '.join(missing) or 'none'}")


if __name__ == "__main__":
    sys.exit(main())
