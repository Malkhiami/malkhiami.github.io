"""Generate data/worldmap.js — a dot-matrix world map as a single SVG path.

Projection: equirectangular, viewBox 1000 x 500 (lon -180..180, lat 90..-90).
Dots are encoded as one path of zero-length segments drawn with round caps.
"""
import json
from pathlib import Path

from shapely.geometry import shape, Point
from shapely.prepared import prep

ROOT = Path(__file__).resolve().parent.parent
GEOJSON = Path(r"C:\Users\miyad\AppData\Local\Temp\claude\C--Users-miyad-Desktop-my-webiste"
               r"\32056798-7f34-4bd7-8373-869595a72375\scratchpad\countries.geo.json")
OUT = ROOT / "data" / "worldmap.js"

STEP = 1.9          # degrees between dots
W, H = 1000, 500


def main() -> None:
    data = json.loads(GEOJSON.read_text(encoding="utf-8"))
    land = [prep(shape(f["geometry"])) for f in data["features"]
            if f.get("id") != "ATA"]  # skip Antarctica

    segments = []
    lat = -56.0
    while lat <= 84.0:
        lon = -180.0
        while lon <= 180.0:
            p = Point(lon, lat)
            if any(g.contains(p) for g in land):
                x = round((lon + 180.0) / 360.0 * W, 1)
                y = round((90.0 - lat) / 180.0 * H, 1)
                segments.append(f"M{x} {y}h.01")
            lon += STEP
        lat += STEP

    path = "".join(segments)
    OUT.write_text(
        "// Generated by scripts/generate_map.py — dot-matrix world map path.\n"
        f"const MAP_DOTS_PATH = \"{path}\";\n",
        encoding="utf-8",
    )
    print(f"{len(segments)} land dots, {OUT.stat().st_size // 1024} KB")


if __name__ == "__main__":
    main()
